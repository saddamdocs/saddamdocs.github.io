/**
 * Writes the import fixtures of PLAN 8 ("Fixtures"): a folder of Markdown and images with the
 * awkward cases import must handle, and a `.zip` of the same with names that only an archive can
 * carry (Windows refuses them on disk, so they stay out of the repository's working tree).
 *
 * Output (committed):
 * - `tests/fixtures/import/source/`: CRLF notes, a byte-order mark, a file that is not UTF-8,
 *   `.obsidian/` and `.trash/` (`.git/` in the zip only), unsupported types, five nested folders, an empty folder (holding only
 *   `.gitkeep`), names with accents and spaces, and PNG, JPEG, GIF, WebP and SVG images.
 * - `tests/fixtures/import/source.zip`: the same, plus `what?.md`, `CON.md`, `trailing dot..md`
 *   and an image `a:b.png` that a note links to.
 *
 * The image over 7 MB is generated by the tests themselves, so the repository stays small.
 * Usage: `node scripts/fixtures.ts`. Needs Playwright's Chromium for the JPEG and WebP bytes.
 *
 * Talks to: the file system, Playwright, fflate. Never to the network.
 */

import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { zipSync } from 'fflate';

const ROOT = fileURLToPath(new URL('../tests/fixtures/import/', import.meta.url));
const SOURCE = join(ROOT, 'source');

/** A 1 × 1 transparent GIF. */
const GIF = Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7', 'base64');
const SVG =
  '<svg xmlns="http://www.w3.org/2000/svg" width="8" height="8"><rect width="8" height="8" fill="#E0A43A"/></svg>\n';

/** Renders a small coloured square to PNG, JPEG and WebP in Chromium. */
async function rasterImages(): Promise<{ png: Buffer; jpeg: Buffer; webp: Buffer }> {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    const urls = await page.evaluate(() => {
      const canvas = document.createElement('canvas');
      canvas.width = 16;
      canvas.height = 16;
      const ctx = canvas.getContext('2d');
      if (ctx === null) throw new Error('no canvas');
      ctx.fillStyle = '#1F3A34';
      ctx.fillRect(0, 0, 16, 16);
      ctx.fillStyle = '#E0A43A';
      ctx.fillRect(4, 4, 8, 8);
      return ['image/png', 'image/jpeg', 'image/webp'].map((t) => canvas.toDataURL(t));
    });
    const bytes = urls.map((u) => Buffer.from(u.split(',')[1] ?? '', 'base64'));
    return { png: bytes[0]!, jpeg: bytes[1]!, webp: bytes[2]! };
  } finally {
    await browser.close();
  }
}

/** Writes a file, creating its folders. */
function put(path: string, data: string | Buffer): void {
  const full = join(SOURCE, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, data);
}

const images = await rasterImages();
rmSync(ROOT, { recursive: true, force: true });

put('Notas/crlf.md', '# Windows line endings\r\n\r\nFirst line.\r\nSecond line.\r\n');
put(
  'Notas/bom.md',
  Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from('Starts with a byte-order mark.\n')]),
);
put('Notas/latin1.md', Buffer.from('Não é UTF-8: ação\n', 'latin1'));
put('Notas/Ação e coração.md', 'Acentos: ação, coração, pão, avó.\n');
put('Notas/日本語のノート.md', 'Non-Latin script.\n');
put('Notas/sub/deep/deeper/deepest/five.md', 'Five folders down.\n');
put('Notas/empty/.gitkeep', '');
put(
  'Notas/with images.md',
  '![png](../images/img.png) ![jpeg](../images/photo.jpg)\n![gif](../images/anim.gif) ![webp](../images/pic.webp) ![svg](../images/logo.svg)\n![missing](../images/nowhere.png)\n',
);
put('images/img.png', images.png);
put('images/photo.jpg', images.jpeg);
put('images/anim.gif', GIF);
put('images/pic.webp', images.webp);
put('images/logo.svg', SVG);
put('README.markdown', 'A `.markdown` note at the top.\n');
put('.obsidian/app.json', '{"legacyEditor": false}\n');
// A `.trash/` folder, as an export with the Trash makes; import skips it. (`.git/` cannot be committed
// inside a repository, so it goes into the zip only.)
put('.trash/old.md', 'From an export that included the Trash.\n');
put('doc.pdf', '%PDF-1.4 not really\n');
put('notes.txt', 'Plain text is not Markdown here.\n');

/** Every file under a folder, as paths relative to it. */
function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [relative(SOURCE, full)];
  });
}

const zipFiles: Record<string, Uint8Array> = {};
for (const path of walk(SOURCE)) zipFiles[path] = new Uint8Array(readFileSync(join(SOURCE, path)));
const encode = (s: string): Uint8Array => new TextEncoder().encode(s);
zipFiles['Bad names/what?.md'] = encode('A question mark in the name.\n');
zipFiles['Bad names/CON.md'] = encode('A reserved Windows name.\n');
zipFiles['Bad names/trailing dot..md'] = encode('Ends with a dot before .md.\n');
zipFiles['Bad names/a:b.png'] = new Uint8Array(images.png);
zipFiles['Bad names/links to it.md'] = encode('![](a:b.png)\n');
zipFiles['.git/HEAD'] = encode('ref: refs/heads/main\n');
zipFiles['Notas/plan.md'] = encode('one\n');
zipFiles['Notas/PLAN.md'] = encode('two: same name, other case\n');
const archive = zipSync(
  Object.fromEntries(
    Object.entries(zipFiles).map(([k, v]) => [k, [v, { mtime: new Date('2026-11-24T12:00:00Z') }]]),
  ),
);
writeFileSync(join(ROOT, 'source.zip'), archive);
console.log(
  `wrote ${String(walk(SOURCE).length)} files in source/ and source.zip (${String(archive.length)} bytes)`,
);
